import { useSearchParams } from "react-router-dom";
import { BarChart3, CheckCircle2, Clock3, Download, Package, XCircle } from "lucide-react";
import {
  PageHeader,
  Stat,
  DeliveryBarChart,
  ChartLegend,
} from "../../components/admin/AdminUI.jsx";
import { DEFAULT_REPORT_YEAR, REPORT_YEARS } from "../../data/reportData.js";
import { jsPDF } from "jspdf";

// The PDF generator is used only by this reports screen.
const SUMMARY = [
  ["Total Bookings", "1,742"],
  ["Completed", "1,128"],
  ["Ongoing", "428"],
  ["Cancelled", "86"],
  ["Success Rate", "94.6%"],
  ["Average Delivery Time", "2h 18m"],
];

const STATUS_BREAKDOWN = [
  ["Completed", "1,128"],
  ["Ongoing", "428"],
  ["Cancelled", "86"],
];

function generateReportPdf(type, year) {
  const doc = new jsPDF();
  const date = new Date().toLocaleDateString("en-PH", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  doc.setFontSize(20);
  doc.setTextColor(7, 86, 168);
  doc.text("GASFAR", 20, 20);

  doc.setFontSize(10);
  doc.setTextColor(70, 80, 95);
  doc.text("LOGISTICS & DELIVERY MANAGEMENT SYSTEM", 20, 28);
  doc.line(20, 34, 190, 34);

  doc.setFontSize(16);
  doc.setTextColor(25, 35, 50);
  doc.text(type, 20, 47);

  doc.setFontSize(9);
  doc.text(`Generated: ${date}`, 20, 54);
  doc.text(`Analytics Year: ${year}`, 20, 61);

  let y = 75;
  SUMMARY.forEach(([label, value]) => {
    doc.text(label, 25, y);
    doc.text(value, 165, y, { align: "right" });
    doc.line(20, y + 4, 190, y + 4);
    y += 16;
  });

  doc.setFontSize(12);
  doc.text("Delivery Status", 20, y + 8);

  doc.setFontSize(9);
  STATUS_BREAKDOWN.forEach(([label, value], index) => {
    doc.text(label, 25, y + 20 + index * 10);
    doc.text(value, 165, y + 20 + index * 10, { align: "right" });
  });

  doc.setFontSize(8);
  doc.text("Generated by GASFAR Administrator", 20, 280);
  doc.text("GASFAR Admin Portal", 190, 280, { align: "right" });

  doc.save(`GASFAR_${type.replaceAll(" ", "_")}_${year}.pdf`);
}

const AVAILABLE_REPORTS = [
  "Monthly Delivery Summary",
  "Driver Performance Report",
  "User Booking Report",
  "Complaint & Incident Report",
];

export default function ReportsPage() {
  // The selected year lives in the URL: /reports?year=2025
  const [searchParams, setSearchParams] = useSearchParams();
  const requested = Number(searchParams.get("year"));
  const year = REPORT_YEARS.includes(requested) ? requested : DEFAULT_REPORT_YEAR;

  const changeYear = (value) =>
    setSearchParams(value === DEFAULT_REPORT_YEAR ? {} : { year: value });

  return (
    <section className="content">
      <PageHeader
        title="Reports & Analytics"
        desc="Generate an actual PDF report for printing, submission, or records."
      >
        <select
          className="yearSelectHeader"
          value={year}
          onChange={(event) => changeYear(Number(event.target.value))}
          aria-label="Select analytics year"
        >
          {REPORT_YEARS.map((y) => (
            <option key={y} value={y}>
              {y}
            </option>
          ))}
        </select>

        <button
          className="primary"
          onClick={() => generateReportPdf("Monthly Delivery Report", year)}
        >
          <Download size={15} />
          Generate PDF
        </button>
      </PageHeader>

      <div className="S">
        <Stat icon={<Package />} label="Monthly Deliveries" value="1,742" change="+9.2%" />
        <Stat icon={<CheckCircle2 />} label="Completed" value="1,128" change="+6.4%" />
        <Stat icon={<XCircle />} label="Cancelled" value="86" change="-2.1%" />
        <Stat icon={<Clock3 />} label="Avg. Delivery Time" value="2h 18m" change="-8.6%" />
      </div>

      <div className="grid2 reportAnalyticsGrid">
        <div className="card reportChartCard">
          <div className="cardHead">
            <div>
              <h2>Monthly Delivery Performance</h2>
              <p>
                {year === 2026
                  ? "Recorded transactions through August 2026"
                  : "Complete transaction history for 2025"}
              </p>
            </div>
          </div>

          <DeliveryBarChart year={year} />
          <ChartLegend className="reportLegend" />
        </div>

        <div className="card reportList reportPageList">
          <div className="cardHead">
            <div>
              <h2>Available Reports</h2>
              <p>Each button creates and downloads a PDF.</p>
            </div>
          </div>

          {AVAILABLE_REPORTS.map((report) => (
            <div className="reportRow" key={report}>
              <div className="reportIcon">
                <BarChart3 size={17} />
              </div>

              <div>
                <b>{report}</b>
                <small>PDF • {year}</small>
              </div>

              <button className="downloadBtn" onClick={() => generateReportPdf(report, year)}>
                <Download size={15} />
              </button>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
